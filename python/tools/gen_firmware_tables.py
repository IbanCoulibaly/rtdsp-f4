#!/usr/bin/env python3
"""Generate firmware/app/generated/fw_tables.{h,c} from the Python design.

Python is the single source of truth for every number baked into the
firmware: the NCO sine table, the boot-time default filter, and the golden
CRCs the power-on self test compares against. The golden values come from
the bit-exact models in rtdsp.fixedpoint, so a POST pass on the target
means target == model, independently of the SIL tests.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from rtdsp import REPO_ROOT, design, fixedpoint, protocol  # noqa: E402
from rtdsp import quantize as Q  # noqa: E402

OUT_DIR = REPO_ROOT / "firmware" / "app" / "generated"
SINE_LUT_BITS = 10
POST_SEED = 0x1234ABCD
POST_LEN = 256


def default_filter() -> Q.FilterDesc:
    """Boot filter: linear-phase low-pass, pass band to 4 kHz, 60 dB stop band from 6 kHz."""
    return Q.fir_q15(design.kaiser_fir(fc=5000, transition_hz=2000, atten_db=60), label="default_lp")


def post_biquad() -> Q.FilterDesc:
    sos = Q.scale_sos_linf(design.butter_sos(4, 2000))
    return Q.biquad_q31(sos, label="post_butter4")


def golden_crc(desc: Q.FilterDesc, x: np.ndarray) -> int:
    y = fixedpoint.engine(desc, x)
    return protocol.crc16_ccitt(y.astype("<i2").tobytes())


def c_array(values, per_line: int, fmt: str) -> str:
    items = [fmt.format(int(v)) for v in values]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return ",\n".join("        " + ln for ln in lines)


def c_desc(name: str, d: Q.FilterDesc) -> str:
    member, fmt, per = {
        Q.FIR_Q15: ("fir_q15", "{:d}", 12),
        Q.BIQUAD_Q31: ("bq_q31", "{:d}", 5),
    }[d.type]
    body = c_array(np.asarray(d.coeffs).ravel(), per, fmt)
    return (f"/* {d.name}: type {Q.TYPE_NAMES[d.type]}, order {d.order}, post_shift {d.post_shift} */\n"
            f"const filter_desc_t {name} = {{\n"
            f"    .type = {d.type}u,\n    .post_shift = {d.post_shift}u,\n    .order = {d.order}u,\n"
            f"    .c.{member} = {{\n{body},\n    }},\n}};\n")


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    n = 1 << SINE_LUT_BITS
    lut = np.round(32767 * np.sin(2 * np.pi * np.arange(n) / n)).astype(np.int16)
    fir = default_filter()
    bq = post_biquad()
    x = fixedpoint.xorshift32_q15(POST_SEED, POST_LEN)
    crc_fir, crc_bq = golden_crc(fir, x), golden_crc(bq, x)

    banner = "/* GENERATED by python/tools/gen_firmware_tables.py -- do not edit. */\n"
    header = f"""{banner}#ifndef FW_TABLES_H
#define FW_TABLES_H

#include "dsp/filter_engine.h"

#define SINE_LUT_BITS {SINE_LUT_BITS}u
#define SINE_LUT_SIZE (1u << SINE_LUT_BITS)
extern const q15_t k_sine_lut[SINE_LUT_SIZE];

/* Active at boot until the host uploads a filter. */
extern const filter_desc_t k_default_filter;
/* Exercised by the power-on self test only. */
extern const filter_desc_t k_post_biquad_q31;

#define POST_INPUT_SEED 0x{POST_SEED:08X}u
#define POST_INPUT_LEN {POST_LEN}u
#define POST_FIR_Q15_CRC 0x{crc_fir:04X}u
#define POST_BIQUAD_Q31_CRC 0x{crc_bq:04X}u

#endif /* FW_TABLES_H */
"""
    source = (f"{banner}#include \"fw_tables.h\"\n\n"
              f"const q15_t k_sine_lut[SINE_LUT_SIZE] = {{\n{c_array(lut, 12, '{:d}')},\n}};\n\n"
              f"{c_desc('k_default_filter', fir)}\n{c_desc('k_post_biquad_q31', bq)}")
    (OUT_DIR / "fw_tables.h").write_text(header)
    (OUT_DIR / "fw_tables.c").write_text(source)
    print(f"default FIR: {fir.order} taps | POST biquad: {bq.order} stages, post_shift {bq.post_shift}")
    print(f"golden CRC: FIR 0x{crc_fir:04X}, biquad 0x{crc_bq:04X} -> {OUT_DIR.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
